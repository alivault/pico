/**
 * The SSH transport: one OpenSSH ControlMaster connection for each machine.
 *
 * All commands and forwards share the master, so the user authenticates one
 * time only (`pico-app machine add` or `reconnect`, in a terminal). The hub
 * starts and uses the master with `BatchMode=yes`: it never asks for input.
 * A connection that needs a password, a passphrase, or a host-key approval
 * fails, and the machine shows **Attention**.
 *
 * The remote Pico listens on its own `127.0.0.1`. The master forwards a local
 * Unix socket (mode 0600 in a 0700 directory) to it, so there are no port
 * conflicts and other users of this computer cannot connect.
 */
import { spawn } from "node:child_process"
import { createHash } from "node:crypto"
import {
  closeSync,
  existsSync,
  mkdirSync,
  openSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs"
import { Agent } from "node:http"
import { createServer } from "node:net"
import { tmpdir } from "node:os"
import { join } from "node:path"

import { machineDir, type MachineProfile } from "./profiles.ts"
import {
  lastLines,
  shellQuote,
  TransportError,
  type Endpoint,
  type ExecResult,
  type MachineTransport,
} from "./transport.ts"

/** macOS allows 104 bytes; SSH adds a temporary suffix to the control path. */
const MAX_SOCKET_PATH = 80

/** A short socket path: in the machine directory, or in `$TMPDIR/pico-ssh`. */
export function socketPath(dir: string, name: string) {
  const preferred = join(dir, name)
  if (Buffer.byteLength(preferred) <= MAX_SOCKET_PATH) return preferred
  const hash = createHash("sha256").update(preferred).digest("hex").slice(0, 16)
  for (const base of [tmpdir(), "/tmp"]) {
    const short = join(base, "pico-ssh", `${hash}-${name}`)
    if (Buffer.byteLength(short) <= MAX_SOCKET_PATH) {
      mkdirSync(join(base, "pico-ssh"), { recursive: true, mode: 0o700 })
      return short
    }
  }
  return preferred
}

/**
 * An SSH config that reads the user's config first. SSH uses the first value
 * that it finds for an option, so these defaults apply only when the user did
 * not set them.
 */
export function sshConfigText() {
  return [
    "# Generated by Pico. Your own SSH config applies first.",
    "Include ~/.ssh/config",
    ...(existsSync("/etc/ssh/ssh_config")
      ? ["Include /etc/ssh/ssh_config"]
      : []),
    "",
    "Host *",
    "  ControlPersist 600",
    "  ServerAliveInterval 15",
    "  ServerAliveCountMax 3",
    "  ConnectTimeout 15",
    "",
  ].join("\n")
}

function writeSshConfig(machinesDir: string) {
  mkdirSync(machinesDir, { recursive: true, mode: 0o700 })
  const file = join(machinesDir, "ssh_config")
  const text = sshConfigText()
  try {
    if (readFileSync(file, "utf8") === text) return file
  } catch {
    // Write it below.
  }
  writeFileSync(file, text, { mode: 0o600 })
  return file
}

/** A target as `ssh` arguments: `ssh://user@host:2222` becomes `-p 2222 user@host`. */
export function targetArgs(target: string) {
  const match = /^ssh:\/\/([^/]+?)(?::(\d+))?\/?$/.exec(target)
  if (!match) return [target]
  return match[2] ? ["-p", match[2], match[1]!] : [match[1]!]
}

function freePort() {
  return new Promise<number>((resolve, reject) => {
    const server = createServer()
    server.once("error", reject)
    server.listen(0, "127.0.0.1", () => {
      const address = server.address()
      const port = typeof address === "object" && address ? address.port : 0
      server.close(() => resolve(port))
    })
  })
}

export type SshOptions = {
  profile: MachineProfile
  machinesDir: string
  /** Let SSH ask for passwords and host keys (`machine add` in a terminal). */
  interactive?: boolean
  /** The SSH program; tests use a fake. */
  ssh?: string
}

export class SshTransport implements MachineTransport {
  readonly #profile: MachineProfile
  readonly #dir: string
  readonly #config: string
  readonly #control: string
  readonly #api: string
  readonly #log: string
  readonly #interactive: boolean
  readonly #ssh: string
  readonly #agent = new Agent({ keepAlive: true })
  #attachedPort: number | undefined
  readonly #forwards = new Set<string>()

  constructor(options: SshOptions) {
    this.#profile = options.profile
    this.#dir = machineDir(options.machinesDir, options.profile.id)
    this.#config = writeSshConfig(options.machinesDir)
    this.#control = socketPath(this.#dir, "ssh.sock")
    this.#api = socketPath(this.#dir, "api.sock")
    this.#log = join(this.#dir, "ssh.log")
    this.#interactive = Boolean(options.interactive)
    this.#ssh = options.ssh ?? "ssh"
  }

  get controlPath() {
    return this.#control
  }

  #base(extra: string[] = []) {
    return [
      "-F",
      this.#config,
      "-o",
      `ControlPath=${this.#control}`,
      "-o",
      `BatchMode=${this.#interactive ? "no" : "yes"}`,
      ...extra,
    ]
  }

  #run(
    args: string[],
    options: {
      timeoutMs?: number
      signal?: AbortSignal
      /** Show the errors in the terminal (interactive commands). */
      echo?: boolean
    } = {}
  ) {
    return new Promise<ExecResult>((resolve, reject) => {
      const child = spawn(this.#ssh, args, {
        stdio: ["ignore", "pipe", "pipe"],
      })
      let stdout = ""
      let stderr = ""
      child.stdout.on("data", (chunk: Buffer) => {
        stdout += chunk.toString("utf8")
      })
      child.stderr.on("data", (chunk: Buffer) => {
        stderr += chunk.toString("utf8")
        if (options.echo) process.stderr.write(chunk)
      })
      const timer = options.timeoutMs
        ? setTimeout(() => child.kill("SIGTERM"), options.timeoutMs)
        : undefined
      const abort = () => child.kill("SIGTERM")
      options.signal?.addEventListener("abort", abort, { once: true })
      child.once("error", (error) => {
        if (timer) clearTimeout(timer)
        options.signal?.removeEventListener("abort", abort)
        reject(
          (error as NodeJS.ErrnoException).code === "ENOENT"
            ? new TransportError(
                "The ssh command was not found. Install OpenSSH.",
                127,
                ""
              )
            : error
        )
      })
      child.once("close", (code, signal) => {
        if (timer) clearTimeout(timer)
        options.signal?.removeEventListener("abort", abort)
        resolve({
          code: code ?? (signal ? 124 : 1),
          stdout,
          stderr,
        })
      })
    })
  }

  async #check() {
    const result = await this.#run(
      [...this.#base(), "-O", "check", ...targetArgs(this.#profile.target)],
      { timeoutMs: 5000 }
    ).catch(() => undefined)
    return result?.code === 0
  }

  async connect(signal: AbortSignal) {
    if (await this.#check()) return
    // A stale socket from a crashed master turns off multiplexing.
    try {
      unlinkSync(this.#control)
    } catch {
      // There is no socket.
    }
    if (signal.aborted) throw new Error("Aborted")
    // `-f` goes to the background after authentication. The master keeps
    // its stderr, so it writes to a file, not to a pipe that closes.
    const log = openSync(this.#log, "w", 0o600)
    const code = await new Promise<number>((resolve, reject) => {
      const child = spawn(
        this.#ssh,
        [
          ...this.#base([
            "-o",
            "ControlMaster=yes",
            "-o",
            "ExitOnForwardFailure=yes",
          ]),
          "-f",
          "-N",
          ...targetArgs(this.#profile.target),
        ],
        {
          stdio: [
            this.#interactive ? "inherit" : "ignore",
            "ignore",
            this.#interactive ? "inherit" : log,
          ],
        }
      )
      const abort = () => child.kill("SIGTERM")
      signal.addEventListener("abort", abort, { once: true })
      const timer = setTimeout(
        () => child.kill("SIGTERM"),
        this.#interactive ? 10 * 60_000 : 45_000
      )
      child.once("error", (error) => {
        clearTimeout(timer)
        signal.removeEventListener("abort", abort)
        reject(
          (error as NodeJS.ErrnoException).code === "ENOENT"
            ? new TransportError(
                "The ssh command was not found. Install OpenSSH.",
                127,
                ""
              )
            : error
        )
      })
      // `exit`, not `close`: the master in the background keeps the file.
      child.once("exit", (exitCode, exitSignal) => {
        clearTimeout(timer)
        signal.removeEventListener("abort", abort)
        resolve(exitCode ?? (exitSignal ? 124 : 1))
      })
    }).finally(() => closeSync(log))
    if (code === 0 && (await this.#check())) return
    let stderr = ""
    try {
      stderr = readFileSync(this.#log, "utf8")
    } catch {
      // No errors were written.
    }
    throw new TransportError(
      lastLines(stderr, 1) ||
        `ssh ${this.#profile.target} failed with exit code ${code}`,
      code,
      lastLines(stderr, 12)
    )
  }

  async exec(
    argv: string[],
    options: { timeoutMs?: number; signal?: AbortSignal } = {}
  ) {
    return this.#run(
      [
        ...this.#base(["-o", "ControlMaster=no"]),
        ...targetArgs(this.#profile.target),
        "--",
        argv.map(shellQuote).join(" "),
      ],
      {
        timeoutMs: options.timeoutMs ?? 30_000,
        echo: this.#interactive,
        ...(options.signal ? { signal: options.signal } : {}),
      }
    )
  }

  async #mux(operation: "forward" | "cancel", spec: string) {
    return this.#run(
      [
        ...this.#base(),
        "-O",
        operation,
        "-L",
        spec,
        ...targetArgs(this.#profile.target),
      ],
      { timeoutMs: 10_000 }
    )
  }

  async attach(remotePort: number) {
    if (this.#attachedPort === remotePort && existsSync(this.#api)) return
    const ports = new Set([remotePort])
    if (this.#attachedPort !== undefined) ports.add(this.#attachedPort)
    for (const port of ports)
      await this.#mux("cancel", `${this.#api}:127.0.0.1:${port}`).catch(
        () => undefined
      )
    try {
      unlinkSync(this.#api)
    } catch {
      // There is no socket.
    }
    const result = await this.#mux(
      "forward",
      `${this.#api}:127.0.0.1:${remotePort}`
    )
    if (result.code !== 0)
      throw new TransportError(
        lastLines(result.stderr, 1) || "SSH could not forward the Pico port",
        result.code,
        lastLines(result.stderr)
      )
    this.#attachedPort = remotePort
  }

  endpoint(): Endpoint {
    return { socketPath: this.#api }
  }

  agent() {
    return this.#agent
  }

  async forward(remotePort: number) {
    const localPort = await freePort()
    const spec = `127.0.0.1:${localPort}:127.0.0.1:${remotePort}`
    const result = await this.#mux("forward", spec)
    if (result.code !== 0)
      throw new TransportError(
        lastLines(result.stderr, 1) ||
          `SSH could not forward port ${remotePort}`,
        result.code,
        lastLines(result.stderr)
      )
    this.#forwards.add(spec)
    return {
      localPort,
      close: async () => {
        if (!this.#forwards.delete(spec)) return
        await this.#mux("cancel", spec).catch(() => undefined)
      },
    }
  }

  async close(options: { exit?: boolean } = {}) {
    this.#agent.destroy()
    const specs = [...this.#forwards]
    this.#forwards.clear()
    if (this.#attachedPort !== undefined)
      specs.push(`${this.#api}:127.0.0.1:${this.#attachedPort}`)
    this.#attachedPort = undefined
    await Promise.all(
      specs.map((spec) => this.#mux("cancel", spec).catch(() => undefined))
    )
    try {
      unlinkSync(this.#api)
    } catch {
      // There is no socket.
    }
    if (options.exit)
      await this.#run(
        [...this.#base(), "-O", "exit", ...targetArgs(this.#profile.target)],
        { timeoutMs: 5000 }
      ).catch(() => undefined)
  }
}
